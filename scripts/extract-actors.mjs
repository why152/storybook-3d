#!/usr/bin/env node
/**
 * Deterministic, dependency-free SVG actor extraction for our five original
 * hand-authored chapters. All painting originates in characters.svg.
 *
 * Usage:
 *   node scripts/extract-actors.mjs --check  # CI: verify exact source parity
 *   node scripts/extract-actors.mjs --write  # refresh all registered sprites
 *
 * No expensive model needed for this repetitive work.
 *
 * The final manifest actor receives any additional root-level <g> groups
 * (GROW has a watering can and independent droplets). Fail closed if the
 * canonical SVG contains unassigned painted content outside those groups.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { mkdirSync } from 'node:fs';

const root=process.cwd();
const scenes=['hello','grow','together','dream','wish'];
const write=process.argv.includes('--write');
if(process.argv.some(v=>v.startsWith('--')&&!['--write','--check'].includes(v))){
  throw new Error('Use --check or --write');
}
if(process.argv.includes('--check')&&write)throw new Error('Specify only one mode.');
let verified=0;
const errors=[];

function tokenize(original,file){
  const defs=original.match(/<defs\b[\s\S]*?<\/defs>/)?.[0];
  const close=original.lastIndexOf('</svg>');
  if(!defs||close<0)throw Error(file+': missing defs or svg closing tag');
  const body=original.slice(original.indexOf(defs)+defs.length,close);
  // This intentionally matches only the outermost <g> wrappers: nested
  // illustrations can contain other groups without splitting body parts.
  const parts=[];let depth=0,start=-1;
  for(const token of body.matchAll(/<\/?g(?:\s[^>]*?)?>/g)){
    if(token[0].startsWith('</')){
      depth--;
      if(depth<0)throw Error(file+': group stack underflow');
      if(depth===0)parts.push({start,end:token.index+token[0].length,
        content:body.slice(start,token.index+token[0].length)});
    }else{
      if(depth===0)start=token.index;
      depth++;
    }
  }
  if(depth)throw Error(file+': unclosed <g>');
  let cursor=0,unassigned='';
  for(const part of parts){
    unassigned+=body.slice(cursor,part.start);
    cursor=part.end;
  }
  unassigned+=body.slice(cursor);
  unassigned=unassigned.replace(/<!--[\s\S]*?-->/g,'').trim();
  if(unassigned)throw Error(file+': top-level drawing not assigned to actor groups: '+unassigned.slice(0,70));
  return {defs,parts:parts.map(x=>x.content)};
}

for(const scene of scenes){
  try{
    const folder=resolve(root,'public/assets',scene);
    const manifest=JSON.parse(readFileSync(resolve(folder,'manifest.json'),'utf8'));
    const actors=manifest.actors;
    if(!Array.isArray(actors)||actors.length<2)throw Error('Missing actor manifest');
    const raw=readFileSync(resolve(folder,'characters.svg'),'utf8');
    const src=tokenize(raw,scene+'/characters.svg');
    if(src.parts.length<actors.length)throw Error('Too few source groups for actor list');
    for(let i=0;i<actors.length;i++){
      const actor=actors[i],file=resolve(folder,actor.file);
      if(!file.startsWith(folder+'/'))throw Error('Unsafe actor path: '+actor.file);
      const chosen=i===actors.length-1?src.parts.slice(i):[src.parts[i]];
      if(!chosen.length)throw Error('No source group for '+actor.id);
      if(write){
        const output='<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="700" viewBox="0 0 1200 700">\n'+
          src.defs+'\n<!-- Autogenerated actor from original '+scene+'/characters.svg: '+actor.id+' -->\n'+
          chosen.join('\n')+'\n</svg>\n';
        mkdirSync(dirname(file),{recursive:true});
        writeFileSync(file,output,'utf8');
      }else{
        if(!existsSync(file))throw Error('Missing actor: '+actor.file);
        const individual=tokenize(readFileSync(file,'utf8'),actor.file);
        if(individual.defs!==src.defs)throw Error(actor.id+': gradient/texture defs drifted');
        if(individual.parts.length!==chosen.length||
           !chosen.every((g,index)=>g===individual.parts[index]))
          throw Error(actor.id+': original shape changed (or source file stale)');
      }
      verified++;
    }
  }catch(error){
    errors.push(scene+': '+String(error));
  }
}

if(errors.length){
  for(const error of errors)console.error('FAIL '+error);
  process.exitCode=1;
}else{
  console.log((write?'WROTE ':'PASS ')+verified+' original actor sprites from '+scenes.length+
    ' canonical five-story SVG illustrations; original source art remains unchanged.');
}
